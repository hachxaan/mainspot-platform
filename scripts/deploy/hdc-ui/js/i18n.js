let current = "en";

export function setLanguage(lang) {
  current = lang === "es" ? "es" : "en";
  document.documentElement.lang = current;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (STRINGS[current][key]) node.textContent = STRINGS[current][key];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const key = node.getAttribute("data-i18n-aria");
    if (STRINGS[current][key]) node.setAttribute("aria-label", STRINGS[current][key]);
  });
  document.dispatchEvent(new CustomEvent("hdc:language", { detail: current }));
}

export function has(key) {
  return Object.hasOwn(STRINGS[current], key) || Object.hasOwn(STRINGS.en, key);
}

export function t(key, vars) {
  const template = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

export function language() {
  return current;
}
